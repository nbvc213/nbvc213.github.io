import {readFile,readdir,writeFile,stat} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
const args=process.argv.slice(2);
const option=key=>{const i=args.indexOf('--'+key);return i<0?undefined:args[i+1];};
const folder=option('folder'),title=option('title')?.trim();
const base=resolve('content');
if(!folder||!title||dirname(resolve(base,folder))!==base||/[<>:"/\\|?*]/.test(title)||/[. ]$/.test(title))throw new Error('请指定中文分类目录和合法文件名，例如 --folder "Java 笔记" --title "新笔记"；冒号等请用全角字符。');
const directory=resolve(base,folder);
if(!(await stat(directory)).isDirectory())throw new Error('分类目录不存在');
await writeFile(resolve(directory,title+'.md'),`---\ndraft: true\n---\n\n## 开始记录\n\n`,{flag:'wx'});
console.log('已创建草稿：'+resolve(directory,title+'.md')+'；完成后删除 draft: true 即可发布。');
